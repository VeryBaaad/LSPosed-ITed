private val defaultKeyColor = KeyColors.first { it.value == "MATERIAL_BLUE" }

data class SettingsState(
    val themeMode: ThemeMode = ThemeMode.SYSTEM,
    val amoled: Boolean = false,
    val dynamicColor: Boolean = true,
    val keyColor: KeyColor = defaultKeyColor,
    val language: String = "SYSTEM",
    val doh: Boolean = true,
    val updateChannel: String = "CHANNEL_STABLE",
    val wordWrap: Boolean = false,
    val filterSystemApps: Boolean = true,
    val filterGames: Boolean = true,
    val filterModules: Boolean = true,
    val filterDenylist: Boolean = false,
    val listSort: Int = 0,
    val repoSort: Int = 0,
    val upgradableFirst: Boolean = true,
)

/**
 * Single source of truth for preferences. The legacy UI stored everything in the default
 * SharedPreferences, so the keys below are intentionally kept compatible.
 */
object SettingsRepository {
    private val prefs
        get() = App.getPreferences()

    private val _state = MutableStateFlow(readState())
    val state: StateFlow<SettingsState> = _state.asStateFlow()

    private fun readState(): SettingsState {
        val p = prefs
        val colorValue = p.getString("theme_color", defaultKeyColor.value)
            ?: defaultKeyColor.value
        val keyColor = KeyColors.firstOrNull { it.value == colorValue }
            ?: KeyColors.firstOrNull { "MATERIAL_" + colorValue.removePrefix("COLOR_") == it.value }
            ?: defaultKeyColor
        return SettingsState(
            themeMode = ThemeMode.fromValue(p.getString("dark_theme", ThemeMode.SYSTEM.value)),
            amoled = p.getBoolean("black_dark_theme", false),
            dynamicColor = p.getBoolean("follow_system_accent", true),
            keyColor = keyColor,
            language = p.getString("language", "SYSTEM") ?: "SYSTEM",
            doh = p.getBoolean("doh", true),
            updateChannel = p.getString("update_channel", "CHANNEL_STABLE") ?: "CHANNEL_STABLE",
            wordWrap = p.getBoolean("enable_word_wrap", false),
            filterSystemApps = p.getBoolean("filter_system_apps", true),
            filterGames = p.getBoolean("filter_games", true),
            filterModules = p.getBoolean("filter_modules", true),
            filterDenylist = p.getBoolean("filter_denylist", false),
            listSort = p.getInt("list_sort", 0),
            repoSort = p.getInt("repo_sort", 0),
            upgradableFirst = p.getBoolean("upgradable_first", true),
        )
    }

    private inline fun edit(block: (SettingsState) -> SettingsState) {
        _state.update(block)
    }

    fun refresh() {
        _state.value = readState()
    }

    fun setThemeMode(mode: ThemeMode) {
        prefs.edit().putString("dark_theme", mode.value).apply()
        edit { it.copy(themeMode = mode) }
    }

    fun setAmoled(enabled: Boolean) {
        prefs.edit().putBoolean("black_dark_theme", enabled).apply()
        edit { it.copy(amoled = enabled) }
    }

    fun setDynamicColor(enabled: Boolean) {
        prefs.edit().putBoolean("follow_system_accent", enabled).apply()
        edit { it.copy(dynamicColor = enabled) }
    }

    fun setKeyColor(color: KeyColor) {
        prefs.edit().putString("theme_color", color.value).apply()
        edit { it.copy(keyColor = color) }
    }

    fun setLanguage(tag: String) {
        prefs.edit().putString("language", tag).apply()
        edit { it.copy(language = tag) }
    }

    fun setDoh(enabled: Boolean) {
        prefs.edit().putBoolean("doh", enabled).apply()
        App.getOkHttpClient().dns.let { dns ->
            if (dns is org.lsposed.manager.util.CloudflareDNS) dns.DoH = enabled
        }
        edit { it.copy(doh = enabled) }
    }

    fun setUpdateChannel(channel: String) {
        prefs.edit().putString("update_channel", channel).apply()
        edit { it.copy(updateChannel = channel) }
    }

    fun setWordWrap(enabled: Boolean) {
        prefs.edit().putBoolean("enable_word_wrap", enabled).apply()
        edit { it.copy(wordWrap = enabled) }
    }

    fun setFilters(
        systemApps: Boolean = _state.value.filterSystemApps,
        games: Boolean = _state.value.filterGames,
        modules: Boolean = _state.value.filterModules,
        denylist: Boolean = _state.value.filterDenylist,
    ) {
        prefs.edit()
            .putBoolean("filter_system_apps", systemApps)
            .putBoolean("filter_games", games)
            .putBoolean("filter_modules", modules)
            .putBoolean("filter_denylist", denylist)
            .apply()
        edit {
            it.copy(
                filterSystemApps = systemApps,
                filterGames = games,
                filterModules = modules,
                filterDenylist = denylist,
            )
        }
    }

    fun setListSort(sort: Int) {
        prefs.edit().putInt("list_sort", sort).apply()
        edit { it.copy(listSort = sort) }
    }

    fun setRepoSort(sort: Int) {
        prefs.edit().putInt("repo_sort", sort).apply()
        edit { it.copy(repoSort = sort) }
    }

    fun setUpgradableFirst(enabled: Boolean) {
        prefs.edit().putBoolean("upgradable_first", enabled).apply()
        edit { it.copy(upgradableFirst = enabled) }
    }
}

fun KeyColor.argb(): Int = color.toArgb()
