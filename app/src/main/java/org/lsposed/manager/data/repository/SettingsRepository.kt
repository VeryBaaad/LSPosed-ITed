enum class ThemeMode(val value: String) {
    SYSTEM("MODE_NIGHT_FOLLOW_SYSTEM"),
    LIGHT("MODE_NIGHT_NO"),
    DARK("MODE_NIGHT_YES");

    companion object {
        fun fromValue(value: String?): ThemeMode =
            entries.firstOrNull { it.value == value } ?: SYSTEM
    }
}

